# Programa: Ejemplo de caracteres especiales en Python

#Salto de linea \n
mensaje1 = "Hola\nMundo"
print(mensaje1)

# Tabulacion \t
# mprimimos una guia numerica para ver las posiciones
print("1234123412341234123412341234")
mesaje2 = "\tJuan Perez"
print(mesaje2)

# Comillas dentro de cadenas
mensaje3 = "Ella dijo \"Hola a Todos\""
print(mensaje3)

# Barra invertida \
mensaje4 = "c:\\Usuarios\\Marce\\Documentos"
print(mensaje4)

# Cadena cruda (raw string) r
mensaje5 = r"C:\Usuarios\Marce\Documentos"
print(mensaje5)

